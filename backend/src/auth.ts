import { createHmac, randomBytes, scrypt, timingSafeEqual, type ScryptOptions } from 'node:crypto'

export const roles = ['viewer', 'operator', 'admin'] as const
export type Role = (typeof roles)[number]

const roleRank: Record<Role, number> = { viewer: 0, operator: 1, admin: 2 }
const usernamePattern = /^[a-zA-Z0-9][a-zA-Z0-9._@-]{0,63}$/
const scryptParameters = { N: 16384, r: 8, p: 1, keyLength: 64 }

export interface UserRecord {
  username: string
  passwordHash: string
  role: Role
}

export interface AuthUser {
  username: string
  role: Role
}

export interface SessionPayload {
  sub: string
  iat: number
  exp: number
  /** Session version of a console-managed user; a password reset or disable bumps it. */
  ver?: number
}

export function isRole(value: unknown): value is Role {
  return typeof value === 'string' && (roles as readonly string[]).includes(value)
}

export function hasRole(actual: Role, required: Role): boolean {
  return roleRank[actual] >= roleRank[required]
}

export function permissionsFor(role: Role) {
  return {
    read: true,
    operate: hasRole(role, 'operator'),
    administer: hasRole(role, 'admin'),
  }
}

function deriveKey(password: string, salt: Buffer, options: ScryptOptions & { keyLength: number }): Promise<Buffer> {
  const { keyLength, ...scryptOptions } = options
  return new Promise((resolve, reject) => {
    scrypt(password, salt, keyLength, { ...scryptOptions, maxmem: 64 * 1024 * 1024 }, (error, key) => {
      if (error) reject(error)
      else resolve(key)
    })
  })
}

/** Format: scrypt$N$r$p$<salt base64url>$<key base64url> */
export async function hashPassword(password: string): Promise<string> {
  const salt = randomBytes(16)
  const key = await deriveKey(password, salt, scryptParameters)
  const { N, r, p } = scryptParameters
  return ['scrypt', N, r, p, salt.toString('base64url'), key.toString('base64url')].join('$')
}

export function isPasswordHash(value: unknown): value is string {
  if (typeof value !== 'string') return false
  const parts = value.split('$')
  return parts.length === 6 && parts[0] === 'scrypt' && parts.slice(1, 4).every((part) => /^\d+$/.test(part)) && parts[4].length > 0 && parts[5].length > 0
}

export async function verifyPassword(password: string, storedHash: string): Promise<boolean> {
  if (!isPasswordHash(storedHash)) return false
  const [, N, r, p, saltText, keyText] = storedHash.split('$')
  const expected = Buffer.from(keyText, 'base64url')
  const actual = await deriveKey(password, Buffer.from(saltText, 'base64url'), {
    N: Number(N),
    r: Number(r),
    p: Number(p),
    keyLength: expected.length,
  })
  return actual.length === expected.length && timingSafeEqual(actual, expected)
}

export function parseUsers(raw: unknown): UserRecord[] {
  if (!Array.isArray(raw)) throw new Error('The user list must be a JSON array')
  const seen = new Set<string>()
  return raw.map((entry, index) => {
    const user = entry as Partial<UserRecord> | null
    if (!user || typeof user !== 'object') throw new Error('User #' + (index + 1) + ' must be an object')
    if (typeof user.username !== 'string' || !usernamePattern.test(user.username)) throw new Error('User #' + (index + 1) + ' has an invalid username')
    if (!isRole(user.role)) throw new Error('User "' + user.username + '" must have role viewer, operator, or admin')
    if (!isPasswordHash(user.passwordHash)) throw new Error('User "' + user.username + '" needs a passwordHash generated by the users CLI')
    const key = user.username.toLowerCase()
    if (seen.has(key)) throw new Error('User "' + user.username + '" is defined more than once')
    seen.add(key)
    return { username: user.username, passwordHash: user.passwordHash, role: user.role }
  })
}

export function signSession(payload: SessionPayload, secret: string): string {
  const body = Buffer.from(JSON.stringify(payload)).toString('base64url')
  const signature = createHmac('sha256', secret).update(body).digest('base64url')
  return body + '.' + signature
}

export function verifySession(token: string, secret: string, now = Date.now()): SessionPayload | null {
  const [body, signature, extra] = token.split('.')
  if (!body || !signature || extra !== undefined) return null
  const expected = createHmac('sha256', secret).update(body).digest()
  const actual = Buffer.from(signature, 'base64url')
  if (actual.length !== expected.length || !timingSafeEqual(actual, expected)) return null
  try {
    const payload = JSON.parse(Buffer.from(body, 'base64url').toString('utf8')) as Partial<SessionPayload>
    if (typeof payload.sub !== 'string' || typeof payload.iat !== 'number' || typeof payload.exp !== 'number') return null
    if (payload.exp <= now) return null
    if (payload.ver !== undefined && typeof payload.ver !== 'number') return null
    return payload.ver === undefined ? { sub: payload.sub, iat: payload.iat, exp: payload.exp } : { sub: payload.sub, iat: payload.iat, exp: payload.exp, ver: payload.ver }
  } catch {
    return null
  }
}

export function parseCookies(header: string | undefined): Record<string, string> {
  const cookies: Record<string, string> = {}
  for (const part of (header || '').split(';')) {
    const separator = part.indexOf('=')
    if (separator < 1) continue
    const name = part.slice(0, separator).trim()
    const value = part.slice(separator + 1).trim()
    try {
      cookies[name] = decodeURIComponent(value)
    } catch {
      cookies[name] = value
    }
  }
  return cookies
}

/**
 * Browsers always send Origin on cross-site POSTs and WebSocket handshakes. A missing Origin comes from
 * non-browser clients, which cannot replay a user's cookie, so it is accepted.
 */
export function isAllowedOrigin(origin: string | undefined, host: string | undefined, trustedOrigins: string[] = []): boolean {
  if (!origin) return true
  if (trustedOrigins.includes(origin)) return true
  try {
    return Boolean(host) && new URL(origin).host === host
  } catch {
    return false
  }
}

/** Counts failed logins per key inside a sliding window. */
export class LoginThrottle {
  private readonly failures = new Map<string, number[]>()
  private readonly maxFailures: number
  private readonly windowMs: number

  constructor(maxFailures = 5, windowMs = 15 * 60 * 1000) {
    this.maxFailures = maxFailures
    this.windowMs = windowMs
  }

  private recent(key: string, now: number): number[] {
    const attempts = (this.failures.get(key) || []).filter((time) => now - time < this.windowMs)
    if (attempts.length) this.failures.set(key, attempts)
    else this.failures.delete(key)
    return attempts
  }

  retryAfterMs(key: string, now = Date.now()): number {
    const attempts = this.recent(key, now)
    if (attempts.length < this.maxFailures) return 0
    return this.windowMs - (now - attempts[0])
  }

  recordFailure(key: string, now = Date.now()): void {
    if (this.failures.size > 10000) {
      for (const existing of this.failures.keys()) this.recent(existing, now)
    }
    this.failures.set(key, this.recent(key, now).concat(now))
  }

  reset(key: string): void {
    this.failures.delete(key)
  }
}

export type UserSource = 'config' | 'console'

export interface ResolvedUser {
  username: string
  role: Role
  passwordHash: string
  source: UserSource
  sessionVersion?: number
}

/** The subset of ConsoleStore the auth service needs; keeps auth.ts free of SQLite. */
export interface UserLookup {
  getUser(username: string): { username: string; passwordHash: string; role: Role; disabled: boolean; sessionVersion: number } | undefined
}

export interface AuthServiceOptions {
  /** Users from AUTH_USERS_FILE / Helm. They cannot be changed from the UI. */
  users: UserRecord[]
  /** Users created by admins in the UI. */
  store?: UserLookup
  sessionSecret: string
  sessionTtlMs: number
}

export class AuthService {
  readonly sessionTtlMs: number
  private readonly configUsers: Map<string, UserRecord>
  private readonly store?: UserLookup
  private readonly sessionSecret: string
  private readonly fallbackHash: Promise<string>

  constructor(options: AuthServiceOptions) {
    this.configUsers = new Map(options.users.map((user) => [user.username.toLowerCase(), user]))
    this.store = options.store
    this.sessionSecret = options.sessionSecret
    this.sessionTtlMs = options.sessionTtlMs
    // Unknown usernames still pay for one scrypt run so response timing does not reveal valid accounts.
    this.fallbackHash = hashPassword(randomBytes(16).toString('hex'))
  }

  configUserList(): UserRecord[] {
    return [...this.configUsers.values()]
  }

  isConfigUser(username: string): boolean {
    return this.configUsers.has(username.toLowerCase())
  }

  /** Config users win over console users with the same name; disabled console users do not resolve. */
  lookup(username: string): ResolvedUser | undefined {
    const configUser = this.configUsers.get(username.toLowerCase())
    if (configUser) return { ...configUser, source: 'config' }
    const stored = this.store?.getUser(username)
    if (!stored || stored.disabled) return undefined
    return { username: stored.username, role: stored.role, passwordHash: stored.passwordHash, source: 'console', sessionVersion: stored.sessionVersion }
  }

  async authenticate(username: string, password: string): Promise<AuthUser | null> {
    const user = this.lookup(username)
    const valid = await verifyPassword(password, user?.passwordHash ?? await this.fallbackHash)
    return user && valid ? { username: user.username, role: user.role } : null
  }

  issueSession(user: AuthUser, now = Date.now()): { token: string; expiresAt: number } {
    const expiresAt = now + this.sessionTtlMs
    const version = this.lookup(user.username)?.sessionVersion
    const payload: SessionPayload = { sub: user.username, iat: now, exp: expiresAt }
    if (version !== undefined) payload.ver = version
    return { token: signSession(payload, this.sessionSecret), expiresAt }
  }

  /** Resolves the current role on every request, so removing a user or changing a role applies to existing sessions. */
  resolveSession(token: string | undefined, now = Date.now()): (AuthUser & { expiresAt: number }) | null {
    if (!token) return null
    const payload = verifySession(token, this.sessionSecret, now)
    if (!payload) return null
    const user = this.lookup(payload.sub)
    if (!user) return null
    if (user.source === 'console' && payload.ver !== user.sessionVersion) return null
    return { username: user.username, role: user.role, expiresAt: payload.exp }
  }
}
